package pipeline

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"hash"
	"net/netip"
	"path/filepath"

	"vansail-ip-atlas/internal/via3"
)

type compiledKinds struct {
	build  *compiler
	scope  scope
	input  [3]hash.Hash
	keys   [3][32]byte
	reused [3]spatialCacheEntry
}

func (c *compiler) compiledStaticKinds(s scope) *compiledKinds {
	if c.options.compiledReuse == nil || s.asn || s.group != locationFacts && s.group != networkFacts {
		return nil
	}
	return &compiledKinds{build: c, scope: s}
}

// Read the exact accepted private run row before advancing the owned input.
// The ordered frame bytes include the full payload and inherited flag.
func (k *compiledKinds) add(kind uint16, row encoded) {
	if k == nil || kind < 2 || kind > 4 {
		return
	}
	ordinal := kind - 2
	if k.input[ordinal] == nil {
		k.input[ordinal] = sha256.New()
	}
	var length [4]byte
	binary.LittleEndian.PutUint32(length[:], uint32(len(row.data)))
	_, _ = k.input[ordinal].Write(length[:])
	_, _ = k.input[ordinal].Write(row.data)
}

func (k *compiledKinds) lookup(ctx context.Context, kind uint16, dict via3.BuiltObject) (via3.BuiltObject, bool, error) {
	var empty via3.BuiltObject
	if kind < 2 || kind > 4 || !k.scope.group.contains(kind) {
		return empty, false, errFactGroup
	}
	ordinal := kind - 2
	if k.input[ordinal] == nil {
		return empty, false, errSpatialCache
	}
	// The complete current dictionary is generated by the ordinary encoder.
	// Even identical row references are unusable if its ordinals have changed.
	var input [32]byte
	copy(input[:], k.input[ordinal].Sum(nil))
	key, err := spatialReuseKey("compiled-static-kind", struct {
		Input      [32]byte
		Dictionary string
		Prefix     netip.Prefix
		Group      factGroup
		Kind       uint16
	}{input, dict.Info.SHA256, k.scope.prefix, k.scope.group, kind})
	if err != nil {
		return empty, false, err
	}
	k.keys[ordinal] = key
	cache := k.build.options.compiledReuse
	entry, hit, err := cache.Lookup(ctx, "compiled", key)
	if err != nil || !hit {
		return empty, false, err
	}
	compiled := entry.Compiled
	if compiled == nil || len(compiled.Objects) != 1 || len(compiled.Routes) != 1 || compiled.Routes[0].Prefix != k.scope.prefix || len(compiled.Routes[0].ASNs) != 0 || len(compiled.Routes[0].Destinations) != 1 {
		return empty, false, errSpatialCache
	}
	info := compiled.Objects[0]
	if info.Kind != kind || info.Partition != k.scope.name() || compiled.Routes[0].Destinations[0] != info || uint64(info.Bytes) > k.build.options.Limits.ObjectBytes {
		return empty, false, errSpatialCache
	}
	raw, err := hex.DecodeString(info.SHA256)
	if err != nil || len(raw) != sha256.Size {
		return empty, false, errSpatialCache
	}
	var digest [32]byte
	copy(digest[:], raw)
	path, err := cache.ObjectPath(digest)
	if err != nil {
		return empty, false, err
	}
	data, err := cacheRead(ctx, path, int64(info.Bytes))
	if err != nil || len(data) != info.Bytes || sha256.Sum256(data) != digest {
		return empty, false, errors.Join(err, errSpatialCache)
	}
	shard, err := via3.Read(ctx, data)
	if err != nil || shard.Kind != kind {
		return empty, false, errors.Join(err, errSpatialCache)
	}
	if err = via3.ValidatePublicProfile(shard); err != nil {
		return empty, false, err
	}
	if !staticKindDictionary(shard, dict.Info) {
		return empty, false, errSpatialCache
	}
	k.reused[ordinal] = entry
	return via3.BuiltObject{Info: info, Bytes: data, Shard: shard}, true, nil
}

func staticKindDictionary(shard via3.Shard, dict via3.ObjectInfo) bool {
	rows, _ := shard.Rows(7)
	if dict.SHA256 == "" {
		return len(rows) == 0
	}
	if dict.Kind != 14 || dict.Partition != "all" || len(rows) != 40 ||
		binary.LittleEndian.Uint16(rows) != 14 || binary.LittleEndian.Uint32(rows[4:]) != uint32(dict.Bytes) {
		return false
	}
	expected, err := hex.DecodeString(dict.SHA256)
	return err == nil && bytes.Equal(expected, rows[8:])
}

// Retain after the complete grouped leaf passed validation, fit and output
// registration. An attempted encoding which later repacks cannot save a hit.
func (k *compiledKinds) retain(compiled via3.CompiledPartition) error {
	if k == nil {
		return nil
	}
	cache := k.build.options.compiledReuse
	for i, key := range k.keys {
		if key == ([32]byte{}) {
			continue
		}
		entry := k.reused[i]
		if entry.Key != ([32]byte{}) {
			if _, err := cache.Retain(k.build.ctx, entry, nil); err != nil {
				return err
			}
			continue
		}
		output, ok := compiled.Destinations[uint16(i+2)]
		if !ok {
			return errSpatialCache
		}
		info := output.Info
		raw, err := hex.DecodeString(info.SHA256)
		if err != nil || len(raw) != sha256.Size {
			return errSpatialCache
		}
		var digest [32]byte
		copy(digest[:], raw)
		entry = spatialCacheEntry{Domain: "compiled", Key: key, Compiled: &compiledPartitionEntry{
			Objects: []via3.ObjectInfo{info}, Routes: []compiledRoute{{Prefix: k.scope.prefix, Destinations: []via3.ObjectInfo{info}}},
		}}
		files := map[[32]byte]string{digest: filepath.Join(k.build.output, "objects", info.SHA256+".via3")}
		if _, err = cache.Retain(k.build.ctx, entry, files); err != nil {
			return err
		}
	}
	return nil
}
